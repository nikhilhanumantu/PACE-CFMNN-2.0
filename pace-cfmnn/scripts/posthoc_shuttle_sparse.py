"""Post hoc (not pre-registered): why DiCE changes fewer features than PACE-sparse on Shuttle.

Shuttle, seed 40, the same 30 test points, model and DiCE setting as
``run_counterfactuals.py --extended``. For each point where DiCE's valid
answer changes fewer features than PACE-sparse's, it checks:

* whether the point starts inside a box of its own class (membership 1);
* whether moving into the target box with the fewest features outside its
  intervals still leaves the point inside its own box (a tie);
* whether PACE-sparse with every target box as a candidate is still less
  sparse (so the candidate limit is not the cause);
* where DiCE's answer lies: inside a target box or not, and the best own-class
  and target-class memberships there.

Writes ``results/extensions_v1/counterfactuals/posthoc_shuttle.md``.
"""

from __future__ import annotations

import contextlib
import io
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from pace_cfmnn import CFMNN, data  # noqa: E402
from pace_cfmnn import xai_baselines as xb  # noqa: E402
from pace_cfmnn.counterfactual import sparse_counterfactual  # noqa: E402

NAME, SEED, N = "shuttle", 40, 30


def main():
    ds = data.load(NAME, seed=SEED)
    sp = data.paper_split(ds.y, SEED)
    order = np.random.default_rng(SEED).permutation(sp["train"])
    sc = data.fit_scaler(ds.X[order])
    Xtr, ytr = sc.transform(ds.X[order]), ds.y[order]
    te = np.random.default_rng(SEED).permutation(sp["test"])[:N]
    Xte = np.clip(sc.transform(ds.X[te]), 0.0, 1.0)
    model = CFMNN().fit(Xtr, ytr)
    det = model.predict_details(Xte)

    rows, n_valid = [], 0
    for r in range(len(Xte)):
        if det.runner_up[r] < 0:
            continue
        x, target = Xte[r], model.classes_[det.runner_up[r]]
        a, t = det.cls[r], int(np.flatnonzero(model.classes_ == target)[0])
        tb, ab = model.class_boxes_[t], model.class_boxes_[a]
        cs = sparse_counterfactual(model, x, target)
        call = sparse_counterfactual(model, x, target, max_boxes=len(tb))
        with contextlib.redirect_stderr(io.StringIO()):
            cf = xb.dice_counterfactual(model, x, Xtr, ytr, target, seed=SEED, n_cfs=5, sparse=True,
                                        pick="nearest_valid")
        if cf is None:
            continue
        cf = np.asarray(cf, float)
        if model.predict(cf[None])[0] != target:
            continue
        n_valid += 1
        k_s = int((np.abs(cs.x_cf - x) > 1e-9).sum())
        k_all = int((np.abs(call.x_cf - x) > 1e-9).sum())
        k_d = int((np.abs(cf - x) > 1e-9).sum())
        if k_d >= k_s:
            continue
        V, W = model.V_[tb], model.W_[tb]
        clipped = np.clip(x, V, W)
        n_out = (np.abs(clipped - x) > 1e-12).sum(axis=1)
        z = clipped[int(np.argmin(n_out))]
        m_x, m_z, m_cf = (model.memberships(v[None])[0] for v in (x, z, cf))
        rows.append(dict(
            point=int(te[r]), sparse=k_s, sparse_all=k_all, dice=k_d,
            own_x=m_x[ab].max(), own_z=m_z[ab].max(), z_target=bool(model.predict(z[None])[0] == target),
            dice_inside=bool(np.any(np.all((V <= cf + 1e-12) & (cf <= W + 1e-12), axis=1))),
            own_cf=m_cf[ab].max(), tgt_cf=m_cf[tb].max()))

    n = len(rows)
    share = lambda f: sum(bool(f(r)) for r in rows)  # noqa: E731
    L = ["# Post hoc: PACE-sparse vs DiCE on Shuttle (not pre-registered)", "",
         f"Shuttle, seed {SEED}, {N} test points; model, target and DiCE setting as in "
         "`run_counterfactuals.py --extended`. Generated by `scripts/posthoc_shuttle_sparse.py`.", "",
         f"- Points where DiCE's answer is valid: {n_valid}; where it changes fewer features than "
         f"PACE-sparse: {n}.",
         "- Of those:",
         f"  - the point starts inside a box of its own class (membership 1): {share(lambda r: r['own_x'] > 1 - 1e-9)} of {n};",
         f"  - after entering the target box that needs the fewest changes, it is still inside its own "
         f"box (a tie): {share(lambda r: r['own_z'] > 1 - 1e-9)} of {n}; that point is predicted as the "
         f"target in {share(lambda r: r['z_target'])} of {n};",
         f"  - PACE-sparse with every target box as a candidate still changes more features than DiCE: "
         f"{share(lambda r: r['sparse_all'] > r['dice'])} of {n};",
         f"  - DiCE's answer lies inside a target box: {share(lambda r: r['dice_inside'])} of {n};",
         f"  - at DiCE's answer, the own class's best membership is below the target's: "
         f"{share(lambda r: r['own_cf'] < r['tgt_cf'])} of {n} (own at most "
         f"{max(r['own_cf'] for r in rows):.4f}, target at least {min(r['tgt_cf'] for r in rows):.4f}).",
         "", "| Point | Features changed, PACE-sparse / with all target boxes / DiCE | Own membership at x | "
         "Own membership after entering the target box | Own / target membership at DiCE's answer |",
         "|---|---|---|---|---|"]
    for r in rows:
        L.append(f"| {r['point']} | {r['sparse']} / {r['sparse_all']} / {r['dice']} | {r['own_x']:.4f} | "
                 f"{r['own_z']:.4f} | {r['own_cf']:.4f} / {r['tgt_cf']:.4f} |")
    out = ROOT / "results" / "extensions_v1" / "counterfactuals" / "posthoc_shuttle.md"
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
